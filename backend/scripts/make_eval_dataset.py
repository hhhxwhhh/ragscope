# Unanswerable cases carry no gold refs by definition — the corpus is frontend
# documentation, so these are outside it even though they look like normal
# product questions. They measure whether the pipeline refuses instead of
# answering from the model's own knowledge.
UNANSWERABLE: list[str] = [
    "公司差旅住宿的报销标准是多少？",
    "如何申请美国旅游签证？",
    "这份文档里有没有讲 Kubernetes 集群的运维？",
    "员工入职第一年有多少天年假？",
]


async def _resolve(db, kb_id: str, needle: str) -> tuple:
    rows = (
        await db.execute(
            select(Document.id, Document.filename)
            .where(Document.kb_id == kb_id, Document.external_url.ilike(f"%{needle}%"))
        )
    ).all()
    if not rows:
        raise SystemExit(f"没有匹配 {needle} 的文档，先导入对应语料包")
    if len(rows) > 1:
        titles = ", ".join(filename for _, filename in rows)
        raise SystemExit(f"{needle} 匹配到多篇文档（{titles}），请把定位串写精确")
    return rows[0]


async def _chunks_of(db, document_id) -> dict[int, str]:
    rows = (
        await db.execute(
            select(Chunk.chunk_index, Chunk.content).where(Chunk.document_id == document_id)
        )
    ).all()
    return {int(index): (content or "") for index, content in rows}


async def build(kb_id: str) -> None:
    async with SessionLocal() as db:
        kb = await db.get(KnowledgeBase, kb_id)
        if kb is None:
            raise SystemExit(f"找不到知识库 {kb_id}")
        dataset = (
            await db.execute(
                select(EvalDataset).where(
                    EvalDataset.kb_id == kb_id, EvalDataset.name == DATASET_NAME
                )
            )
        ).scalar_one_or_none()
        if dataset is None:
            dataset = EvalDataset(
                kb_id=kb_id,
                name=DATASET_NAME,
                description=DATASET_DESC,
                # The run re-chunks under the dataset's own parameters, so they
                # have to match the KB the labels were annotated against —
                # otherwise chunk indexes silently point somewhere else.
                chunk_size=kb.chunk_size,
                chunk_overlap=kb.chunk_overlap,
            )
            db.add(dataset)
            await db.flush()
        else:
            # Re-running replaces the labels; a stale case pointing at a chunk
            # that no longer exists would silently score zero forever.
            await db.execute(
                EvalCase.__table__.delete().where(EvalCase.dataset_id == dataset.id)
            )

        answerable = 0
        for question, needle, indexes, notes in ANSWERABLE:
            document_id, filename = await _resolve(db, kb_id, needle)
            available = await _chunks_of(db, document_id)
            missing = [index for index in indexes if index not in available]
            if missing:
                raise SystemExit(
                    f"{filename} 缺少标注的 chunk {missing}；"
                    f"切块参数变了请重新标注（现有 {len(available)} 块）"
                )
            db.add(
                EvalCase(
                    dataset_id=dataset.id,
                    question=question,
                    answerable=True,
                    expected_mode="rag",
                    notes=notes,
                    relevant_refs=[
                        {
                            "document_id": str(document_id),
                            "chunk_index": index,
                            "filename": filename,
                        }
                        for index in indexes
                    ],
                )
            )
            answerable += 1

        for question in UNANSWERABLE:
            db.add(
                EvalCase(
                    dataset_id=dataset.id,
                    question=question,
                    answerable=False,
                    expected_mode="rag",
                    notes="语料里确实没有答案，期望拒答",
                    relevant_refs=[],
                )
            )

        await db.commit()
        print(
            f"评测集「{DATASET_NAME}」：可答 {answerable} 条 + "
            f"不可答 {len(UNANSWERABLE)} 条 = {answerable + len(UNANSWERABLE)} 条"
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("kb_id", help="目标知识库 UUID")
    args = parser.parse_args()
    logging.basicConfig(level=logging.WARNING)
    asyncio.run(build(args.kb_id))


if __name__ == "__main__":
    main()
