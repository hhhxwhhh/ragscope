"""Build a hand-labelled evaluation dataset on top of the crawled corpus.

Retrieval metrics are meaningless without gold labels, and gold labels cannot be
generated by the system under test: letting the retriever pick its own gold set
would make every recall number a tautology. So the labels here are **annotated
by hand** — this script only resolves them to ``(document_id, chunk_index)``
pairs in the database and refuses to guess.

How the labels were produced
----------------------------
For each question the target documentation page is fixed first (by URL), then
that page's chunks were read and the ones that literally answer the question
were picked. ``scripts/_inspect_chunks.py`` prints the chunks used for that pass.
A label of two chunks is deliberate: most of these questions are *comparisons*
("X 和 Y 有什么区别"), and the answer is usually split across an intro chunk and
a "limitations / vs" chunk. Labelling only one of them would make recall@1 the
ceiling for a question that genuinely needs two passages.

Usage
-----
    PYTHONPATH=. python scripts/make_eval_dataset.py <kb_id>

Idempotent: re-running replaces the cases of the existing dataset of the same
name instead of creating a duplicate.
"""

